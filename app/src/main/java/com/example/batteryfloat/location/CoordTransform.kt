     *
     * 香港/澳门此前用外接矩形，而矩形在几何上无法与大陆分离——香港最北端 22.5591°N
     * 高于深圳福田 22.5448°N，澳门与珠海拱北/横琴同处一条纬度带——结果深圳主城区与
     * 珠海拱北/横琴被一并划入矩形，这些大陆坐标被跳过 GCJ 偏移（实测偏 603~619 m）。
     * 现按真实边界判定：[inHongKong] 用北部边界线、[inMacau] 用边界多边形。
     * 台湾仍用矩形：已核验厦门/泉州/福州/平潭等大陆点均在矩形外，无同类问题。
     */
    private fun inNonGcjRegion(lat: Double, lng: Double): Boolean =
        inHongKong(lat, lng) || inMacau(lat, lng) ||
            (lng in 119.90..122.01 && lat in 21.87..25.35)      // 台湾（含近岛）

    /**
     * 香港：纬度不高于北部边界线 [hkBorderLat] 时视为香港（无 GCJ 偏移）。
     *
     * 香港是离岛群，用边界多边形需 1300+ 顶点，故改用「经度 → 纬度上限」的北部边界线：
     * 香港领土（含大屿山、长洲、南丫岛、东平洲等全部离岛）全部位于该线以南，
     * 大陆陆地全部位于该线以北，判定只需一次折线插值。
     * 边界线 = 香港官方边界的北向上包络，按 150 m 容差简化后整体北移 200 m：
     * 北移保证香港领土零遗漏，代价是紧贴边界的深圳河/河套带被划入
     * （该带两套官方边界本就互相重叠、实测中位 148 m，且为河道水域与封闭管理区）。
     */
    private fun inHongKong(lat: Double, lng: Double): Boolean {
        if (lat < HK_LAT_MIN || lng < HK_LNG_MIN || lng > HK_LNG_MAX) return false
        // 桂山岛与香港大屿山西南端纬度重叠，靠纬度无法区分，用排除区显式剔除
        // （岛上有常住居民，误判会带来数百米偏移）
        if (lng <= GUISHAN_LNG_MAX && lat <= GUISHAN_LAT_MAX) return false
        return lat <= hkBorderLat(lng)
    }

    /** 香港北部边界线在给定经度上的纬度上限（折线线性插值，两端取端点值不外推） */
    private fun hkBorderLat(lng: Double): Double {
        val last = HK_BORDER.size / 2 - 1
        if (lng <= HK_BORDER[0]) return HK_BORDER[1]
        if (lng >= HK_BORDER[last * 2]) return HK_BORDER[last * 2 + 1]
        var lo = 0
        var hi = last
        while (hi - lo > 1) {
            val mid = (lo + hi) / 2
            if (HK_BORDER[mid * 2] <= lng) lo = mid else hi = mid
        }
        val x1 = HK_BORDER[lo * 2]
        val x2 = HK_BORDER[hi * 2]
        val t = (lng - x1) / (x2 - x1)
        return HK_BORDER[lo * 2 + 1] + t * (HK_BORDER[hi * 2 + 1] - HK_BORDER[lo * 2 + 1])
    }

    /**
     * 澳门：落在边界多边形内时视为澳门（无 GCJ 偏移），奇偶规则判定。
     * 此前的外接矩形会吞掉珠海拱北口岸、湾仔与横琴。
     */
    private fun inMacau(lat: Double, lng: Double): Boolean {
        var inside = false
        for (ring in MACAU_RINGS) {
            var i = 0
            while (i + 3 < ring.size) {
                val ax = ring[i]
                val ay = ring[i + 1]
                val bx = ring[i + 2]
                val by = ring[i + 3]
                if ((ay > lat) != (by > lat) && lng < ax + (lat - ay) * (bx - ax) / (by - ay)) {
                    inside = !inside
                }
                i += 2
            }
        }
        return inside
    }

