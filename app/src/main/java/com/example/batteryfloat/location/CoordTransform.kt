    private const val GUISHAN_LNG_MAX = 113.845
    private const val GUISHAN_LAT_MAX = 22.17

    /**
     * 港澳台地区：无 GCJ 偏移（香港/澳门坐标系统未偏移，台湾用 TWD97 系），
