     * 此前的外接矩形会吞掉珠海拱北口岸、湾仔与横琴。
     */
    private fun inMacau(lat: Double, lng: Double): Boolean {
        var inside = false
        for (ring in MACAU_RINGS) {
            var i = 0
            while (i + 3 < ring.size) {
                val ax = ring[i]
                val ay = ring[i + 1]
                val bx = ring[i + 2]
                val by = ring[i + 3]
                if ((ay > lat) != (by > lat) && lng < ax + (lat - ay) * (bx - ax) / (by - ay)) {
                    inside = !inside
                }
                i += 2
            }
        }
        return inside
    }

