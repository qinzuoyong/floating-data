     * 实测中位 148 m，仍在香港官方边界之内，且为河道水域与封闭管理区）。
     */
    private fun inHongKong(lat: Double, lng: Double): Boolean {
        if (lat < HK_LAT_MIN || lng < HK_LNG_MIN || lng > HK_LNG_MAX) return false
        // 桂山岛与香港大屿山西南端纬度重叠，靠纬度无法区分，用排除区显式剔除
        // （岛上有常住居民，误判会带来数百米偏移）
        if (lng <= GUISHAN_LNG_MAX && lat <= GUISHAN_LAT_MAX) return false
        return lat <= hkBorderLat(lng)
    }

    /** 香港北部边界线在给定经度上的纬度上限（折线线性插值，两端取端点值不外推） */
    private fun hkBorderLat(lng: Double): Double {
        val last = HK_BORDER.size / 2 - 1
        if (lng <= HK_BORDER[0]) return HK_BORDER[1]
        if (lng >= HK_BORDER[last * 2]) return HK_BORDER[last * 2 + 1]
        var lo = 0
        var hi = last
        while (hi - lo > 1) {
            val mid = (lo + hi) / 2
            if (HK_BORDER[mid * 2] <= lng) lo = mid else hi = mid
        }
        val x1 = HK_BORDER[lo * 2]
        val x2 = HK_BORDER[hi * 2]
        val t = (lng - x1) / (x2 - x1)
        return HK_BORDER[lo * 2 + 1] + t * (HK_BORDER[hi * 2 + 1] - HK_BORDER[lo * 2 + 1])
    }

    /**
